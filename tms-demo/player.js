/* TMS timing demo player. Shared by page IV (mounted by iv.js) and tms-demo/index.html.
   Usage: TMSDemo.mount(element, window.TMS_DEMO)
   Data comes from data.js (generated by export_web_demo.py). Styles are prefixed tms- to avoid
   clashing with the site's own classes, and use the site's colour tokens. */
(() => {
  const CSS = `
.tms-player { border: 1px solid var(--ink, #1d1b18); background: #f8f4ec; margin-top: 20px; }
.tms-chips { display: flex; flex-wrap: wrap; gap: 6px; padding: 12px 16px; border-bottom: 1px solid var(--ink, #1d1b18); align-items: center; }
.tms-chips .tms-k { color: var(--ink-2, #5d574c); font-size: 16px; margin-right: 4px; font-variant: small-caps; letter-spacing: .06em; text-transform: lowercase; }
.tms-chip { font: inherit; font-size: 16px; padding: 3px 10px; border: 1px solid var(--rule, #cdc3ae); background: var(--paper, #f4efe4); color: var(--ink, #1d1b18); min-width: 44px; min-height: 32px; cursor: pointer; border-radius: 0; }
.tms-chip:hover { border-color: var(--ink, #1d1b18); }
.tms-chip[aria-pressed="true"] { background: var(--ink, #1d1b18); color: var(--paper, #f4efe4); border-color: var(--ink, #1d1b18); }
.tms-play { font: inherit; margin-left: auto; padding: 3px 16px; font-size: 16px; min-height: 32px; background: var(--ink, #1d1b18); color: var(--paper, #f4efe4); border: 1px solid var(--ink, #1d1b18); cursor: pointer; border-radius: 0; }
.tms-strip { padding: 14px 16px 10px; border-bottom: 1px solid var(--rule, #cdc3ae); }
.tms-head { display: flex; justify-content: space-between; align-items: baseline; gap: 12px; flex-wrap: wrap; margin-bottom: 6px; }
.tms-name { font-size: 19px; }
.tms-name i { display: inline-block; width: 12px; height: 12px; margin-right: 8px; }
.tms-count { color: var(--ink-2, #5d574c); font-size: 17px; }
.tms-count b { color: var(--ink, #1d1b18); font-weight: 600; }
.tms-row { display: grid; grid-template-columns: 1fr 132px; gap: 14px; align-items: center; }
.tms-row canvas { display: block; width: 100%; height: 132px; }
.tms-row svg { display: block; width: 132px; height: 132px; }
.tms-scrub { display: flex; align-items: center; gap: 12px; padding: 10px 16px; border-bottom: 1px solid var(--ink, #1d1b18); }
.tms-scrub label { color: var(--ink-2, #5d574c); font-size: 16px; font-variant: small-caps; letter-spacing: .06em; text-transform: lowercase; }
.tms-scrub input { flex: 1; accent-color: var(--ink, #1d1b18); min-width: 0; }
.tms-scrub .tms-t { color: var(--ink-2, #5d574c); font-size: 16px; min-width: 110px; text-align: right; font-variant-numeric: tabular-nums; }
.tms-verdict { padding: 14px 16px; margin: 0; min-height: 56px; }
.tms-legend { display: flex; flex-wrap: wrap; gap: 6px 20px; color: var(--ink-2, #5d574c); font-size: 16px; margin-top: 10px; }
.tms-legend span { display: inline-flex; align-items: center; gap: 6px; }
.tms-legend svg { display: inline-block; }
.tms-player button:focus-visible, .tms-player input:focus-visible { outline: 2px solid #1f3d5a; outline-offset: 2px; }
@media (max-width: 720px) {
  .tms-row { grid-template-columns: 1fr; }
  .tms-row svg { margin: 0 auto; }
  .tms-play { margin-left: 0; }
  .tms-scrub .tms-t { min-width: 0; }
}`;

  const INK = '#1d1b18', INK2 = '#5d574c', RULE = '#cdc3ae', RAW = '#b9b09c', PAPER2 = '#ebe4d4', BG = '#f8f4ec';
  const COL = { ar: '#1f3d5a', ours: '#7b2d26' };
  const TARGET = Math.PI;
  const wrapA = a => Math.atan2(Math.sin(a), Math.cos(a));
  const isHit = ph => Math.abs(wrapA(ph - TARGET)) < Math.PI / 4;
  const pct = x => Math.round(100 * x) + '%';

  function mount(el, D) {
    if (!document.getElementById('tms-demo-style')) {
      const st = document.createElement('style');
      st.id = 'tms-demo-style';
      st.textContent = CSS;
      document.head.appendChild(st);
    }
    const FS = D.fs, N = D.mu.length, DUR = N / FS;
    const reduce = matchMedia('(prefers-reduced-motion: reduce)').matches;
    let WIN = 2.5, lat = 40, tNow = WIN, playing = !reduce, visible = false, running = false, last = null, vt = 0;

    const strip = (key, name) => `
      <div class="tms-strip">
        <div class="tms-head"><span class="tms-name"><i style="background:${COL[key]}"></i>${name}</span><span class="tms-count" data-count="${key}"></span></div>
        <div class="tms-row"><canvas data-cv="${key}" role="img" aria-label="EEG trace with pulses timed by ${key === 'ours' ? 'our model' : 'the standard method'}"></canvas><svg data-dial="${key}" viewBox="0 0 132 132" role="img" aria-label="Where ${key === 'ours' ? 'our model’s' : 'the standard method’s'} pulses landed on the wave"></svg></div>
      </div>`;
    el.innerHTML = `
      <div class="tms-player">
        <div class="tms-chips" role="group" aria-label="System delay">
          <span class="tms-k">System delay</span>
          ${D.latencies.map(l => `<button class="tms-chip" data-lat="${l}" aria-pressed="${l === lat}">${l} ms</button>`).join('')}
          <button class="tms-play" data-play>Pause</button>
        </div>
        ${strip('ar', 'Standard method: AR forecast')}
        ${strip('ours', 'Ours: personalized neural network')}
        <div class="tms-scrub">
          <label>Time <input type="range" min="0" max="${DUR.toFixed(2)}" step="0.02" value="0" aria-label="Time in the recording"></label>
          <span class="tms-t"></span>
        </div>
        <p class="tms-verdict" aria-live="polite"></p>
      </div>
      <div class="tms-legend">
        <span><svg width="26" height="10" aria-hidden="true"><line x1="0" y1="5" x2="26" y2="5" stroke="${RAW}" stroke-width="1.2"/></svg>raw EEG</span>
        <span><svg width="26" height="10" aria-hidden="true"><line x1="0" y1="5" x2="26" y2="5" stroke="${INK}" stroke-width="2.2"/></svg>true mu rhythm, computed afterwards</span>
        <span><svg width="14" height="12" aria-hidden="true"><path d="M1 1h12L7 11z" fill="${INK}"/></svg>pulse within 45° of the trough</span>
        <span><svg width="14" height="12" aria-hidden="true"><path d="M1.5 1.5h11L7 10.5z" fill="none" stroke="${INK}" stroke-width="1.5"/></svg>pulse that missed</span>
      </div>`;
    // the label wraps the range input; keep the input stretching
    const lab = el.querySelector('.tms-scrub label');
    lab.style.cssText = 'display:flex;align-items:center;gap:12px;flex:1';

    const q = s => el.querySelector(s);
    const cvs = { ar: q('[data-cv="ar"]'), ours: q('[data-cv="ours"]') };
    const scrub = q('.tms-scrub input'), tLabel = q('.tms-t'), playBtn = q('[data-play]'), verdictEl = q('.tms-verdict');

    el.addEventListener('click', e => {
      const b = e.target.closest('button');
      if (!b || !el.contains(b)) return;
      if (b.dataset.lat) {
        lat = +b.dataset.lat;
        el.querySelectorAll('[data-lat]').forEach(x => x.setAttribute('aria-pressed', x === b));
        draw(true);
      } else if ('play' in b.dataset) setPlay(!playing);
    });
    scrub.addEventListener('input', () => { tNow = Math.max(0.05, +scrub.value); draw(true); });

    function setPlay(p) {
      playing = p;
      playBtn.textContent = p ? 'Pause' : 'Play';
      playBtn.setAttribute('aria-label', p ? 'Pause the demo' : 'Play the demo');
      kick();
    }
    function kick() {
      if (playing && visible && !running) { running = true; last = null; requestAnimationFrame(tick); }
    }
    function tick(ts) {
      if (!playing || !visible) { running = false; return; }
      if (last !== null) tNow += Math.min(0.1, (ts - last) / 1000);
      last = ts;
      if (tNow > DUR) tNow = WIN;
      draw(false);
      if (ts - vt > 1000) { vt = ts; verdict(); }
      requestAnimationFrame(tick);
    }

    function fit() {
      const dpr = window.devicePixelRatio || 1;
      for (const c of Object.values(cvs)) {
        const r = c.getBoundingClientRect();
        c.width = Math.max(1, Math.round(r.width * dpr));
        c.height = Math.max(1, Math.round(r.height * dpr));
        c.getContext('2d').setTransform(dpr, 0, 0, dpr, 0, 0);
      }
      WIN = cvs.ar.clientWidth && cvs.ar.clientWidth < 560 ? 1.5 : 2.5;
      if (tNow < WIN) tNow = WIN;
    }

    function drawStrip(key) {
      const c = cvs[key], ctx = c.getContext('2d');
      const w = c.clientWidth, h = c.clientHeight;
      if (!w) return;
      ctx.clearRect(0, 0, w, h);
      const t1 = Math.max(tNow, WIN), t0 = t1 - WIN;
      const X = t => (t - t0) / WIN * w;
      const mid = h * 0.5, sy = h * 0.40 / 1000;
      const Y = v => mid - Math.max(-1250, Math.min(1250, v)) * sy;
      ctx.strokeStyle = RULE; ctx.fillStyle = INK2; ctx.lineWidth = 1; ctx.font = '13px "EB Garamond", Georgia, serif';
      for (let s = Math.ceil(t0); s <= t1; s++) {
        const x = Math.round(X(s)) + 0.5;
        ctx.beginPath(); ctx.moveTo(x, h - 14); ctx.lineTo(x, h - 8); ctx.stroke();
        ctx.fillText(s + ' s', Math.min(x + 3, w - 24), h - 1);
      }
      const i0 = Math.max(0, Math.floor(t0 * FS)), i1 = Math.min(N - 1, Math.floor(tNow * FS));
      const line = (arr, col, lw) => {
        ctx.strokeStyle = col; ctx.lineWidth = lw; ctx.lineJoin = 'round'; ctx.beginPath();
        for (let i = i0; i <= i1; i++) { const x = X(i / FS), y = Y(arr[i]); i === i0 ? ctx.moveTo(x, y) : ctx.lineTo(x, y); }
        ctx.stroke();
      };
      line(D.raw, RAW, 1.1);
      line(D.mu, INK, 2.2);
      if (tNow < DUR) { ctx.strokeStyle = RULE; ctx.setLineDash([3, 3]); ctx.beginPath(); ctx.moveTo(X(tNow) - 0.5, 4); ctx.lineTo(X(tNow) - 0.5, h - 18); ctx.stroke(); ctx.setLineDash([]); }
      for (const [s, ph] of D.pulses[lat][key]) {
        if (s < i0 || s > i1) continue;
        const x = X(s / FS), y = Y(D.mu[s]);
        ctx.beginPath(); ctx.moveTo(x - 6.5, y - 13); ctx.lineTo(x + 6.5, y - 13); ctx.lineTo(x, y - 1.5); ctx.closePath();
        if (isHit(ph)) { ctx.fillStyle = COL[key]; ctx.fill(); ctx.strokeStyle = BG; ctx.lineWidth = 1; ctx.stroke(); }
        else { ctx.fillStyle = BG; ctx.fill(); ctx.strokeStyle = COL[key]; ctx.lineWidth = 1.8; ctx.stroke(); }
      }
    }

    const NB = 24, CX = 66, CY = 66, R0 = 7, R1 = 52;
    const pt = (a, r) => [CX + r * Math.sin(a), CY - r * Math.cos(a)];
    const f1 = v => v.toFixed(1);
    function wedge(a0, a1, r0, r1) {
      const [x0, y0] = pt(a0, r0), [x1, y1] = pt(a0, r1), [x2, y2] = pt(a1, r1), [x3, y3] = pt(a1, r0);
      return `M${f1(x0)} ${f1(y0)}L${f1(x1)} ${f1(y1)}A${r1} ${r1} 0 0 1 ${f1(x2)} ${f1(y2)}L${f1(x3)} ${f1(y3)}A${r0} ${r0} 0 0 0 ${f1(x0)} ${f1(y0)}Z`;
    }
    function drawDial(key, list) {
      const cnt = new Array(NB).fill(0);
      for (const ph of list) { const a = wrapA(ph - TARGET); cnt[Math.min(NB - 1, Math.floor((a + Math.PI) / (2 * Math.PI) * NB))]++; }
      const mx = Math.max(4, ...cnt);
      let s = `<path d="${wedge(-Math.PI / 4, Math.PI / 4, 0.01, R1 + 4)}" fill="${PAPER2}"/>`;
      s += `<circle cx="${CX}" cy="${CY}" r="${R1}" fill="none" stroke="${RULE}"/><circle cx="${CX}" cy="${CY}" r="${(R0 + R1) / 2}" fill="none" stroke="${RULE}" stroke-dasharray="2 3"/>`;
      cnt.forEach((n, i) => {
        if (!n) return;
        const a0 = -Math.PI + i * 2 * Math.PI / NB, a1 = a0 + 2 * Math.PI / NB;
        s += `<path d="${wedge(a0 + 0.02, a1 - 0.02, R0, R0 + (R1 - R0) * n / mx)}" fill="${COL[key]}"/>`;
      });
      s += `<text x="${CX}" y="9" text-anchor="middle" font-size="12" fill="${INK2}" font-family="EB Garamond, serif">trough</text>`;
      s += `<text x="${CX}" y="130" text-anchor="middle" font-size="12" fill="${INK2}" font-family="EB Garamond, serif">peak</text>`;
      q(`[data-dial="${key}"]`).innerHTML = s;
    }

    function stats() {
      const upto = Math.floor(tNow * FS), st = {};
      for (const key of ['ar', 'ours']) {
        const seen = D.pulses[lat][key].filter(([s]) => s <= upto).map(([, ph]) => ph);
        st[key] = { seen, hits: seen.filter(isHit).length };
      }
      return st;
    }
    function draw(updateVerdict) {
      const st = stats();
      for (const key of ['ar', 'ours']) {
        drawStrip(key);
        const { seen, hits } = st[key];
        q(`[data-count="${key}"]`).innerHTML = seen.length ? `<b>${hits} of ${seen.length}</b> on target (${pct(hits / seen.length)})` : 'waiting for the first pulse';
        drawDial(key, seen);
      }
      scrub.value = tNow.toFixed(2);
      tLabel.textContent = `${tNow.toFixed(1)} of ${DUR.toFixed(0)} s`;
      if (updateVerdict || !playing) verdict();
    }
    // Summary for the selected delay (the live clip counts are in each strip's header).
    function verdict() {
      const k = D.latencies.indexOf(lat), R = D.results;
      const text = `At a ${lat} ms delay, across all 9 people: ours lands ${pct(R.cnn_personal.mean[k])} of pulses on target, the standard method ${pct(R.ar.mean[k])}, untimed TMS 25%.`;
      if (verdictEl.textContent !== text) verdictEl.textContent = text;
    }

    // Redraw on resize (also fires when page IV goes from hidden to shown).
    new ResizeObserver(() => { fit(); draw(false); }).observe(cvs.ar);
    // Only animate while the player is on screen.
    new IntersectionObserver(([e]) => { visible = e.isIntersecting; kick(); }).observe(el);
    setPlay(playing);
    fit();
    draw(true);
  }

  window.TMSDemo = { mount };
})();
